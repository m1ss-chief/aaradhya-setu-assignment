'use client';

import { useEffect, useState } from 'react';
import Link from 'next/link';
import { STATUSES } from '@/lib/workflow.js';
import { StatusBadge, formatDate, ErrorNote, api } from '@/components/ui.js';

export default function NotificationsPage() {
  const [status, setStatus] = useState('all');
  const [items, setItems] = useState(null);
  const [error, setError] = useState('');

  useEffect(() => {
    setItems(null);
    const qs = status === 'all' ? '' : `?status=${encodeURIComponent(status)}`;
    api(`/api/notifications${qs}`)
      .then((d) => setItems(d.notifications))
      .catch((e) => setError(e.message));
  }, [status]);

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Notification history</h1>
          <p className="muted">Every WhatsApp message generated by the workflow (mock delivery).</p>
        </div>
        <select value={status} onChange={(e) => setStatus(e.target.value)} aria-label="Filter by status" className="btn">
          <option value="all">All steps</option>
          {STATUSES.slice(1).map((s) => (
            <option key={s}>{s}</option>
          ))}
        </select>
      </div>
      <ErrorNote error={error} />
      <div className="stack">
        {items === null && <div className="card"><div className="skeleton" /><div className="skeleton" /></div>}
        {items?.length === 0 && <p className="empty card">No messages yet.</p>}
        {items?.map((n) => (
          <article key={n.id} className="card" style={{ padding: 16 }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap', marginBottom: 8 }}>
              <span>
                <Link href={`/bookings/${n.bookingId}`} className="mono">
                  {n.bookingId}
                </Link>{' '}
                · {n.devoteeName} · {n.to}
              </span>
              <span>
                <StatusBadge status={n.status} /> <span className="muted" style={{ fontSize: 13 }}>{formatDate(n.createdAt, true)}</span>
              </span>
            </div>
            <div className="chat">
              <div className="bubble">{n.message}</div>
            </div>
          </article>
        ))}
      </div>
    </>
  );
}
