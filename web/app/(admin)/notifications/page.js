'use client';

import { Suspense, useCallback, useEffect, useState } from 'react';
import Link from 'next/link';
import { useSearchParams } from 'next/navigation';
import { ALL_STATUSES } from '@/lib/workflow.js';
import { StatusBadge, ErrorNote, api } from '@/components/ui.js';
import MessageBubble from '@/components/message-bubble.js';
import { useAdmin } from '@/components/admin-context.js';

function NotificationsList() {
  const params = useSearchParams();
  const { can } = useAdmin();
  const [status, setStatus] = useState('all');
  const [delivery, setDelivery] = useState(params.get('delivery') === 'failed' ? 'failed' : 'all');
  const [items, setItems] = useState(null);
  const [error, setError] = useState('');
  const [toast, setToast] = useState('');

  const load = useCallback(() => {
    const qs = new URLSearchParams();
    if (status !== 'all') qs.set('status', status);
    if (delivery !== 'all') qs.set('delivery', delivery);
    return api(`/api/notifications?${qs}`)
      .then((d) => setItems(d.notifications))
      .catch((e) => setError(e.message));
  }, [status, delivery]);

  useEffect(() => {
    setItems(null);
    load();
  }, [load]);

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Notification history</h1>
          <p className="muted">Every WhatsApp message generated by the workflow (mock delivery).</p>
        </div>
        <div className="head-actions">
          <div className="segmented" role="group" aria-label="Delivery">
            <button className={delivery === 'all' ? 'on' : ''} onClick={() => setDelivery('all')}>
              All
            </button>
            <button className={delivery === 'failed' ? 'on' : ''} onClick={() => setDelivery('failed')}>
              Failed only
            </button>
          </div>
          <select value={status} onChange={(e) => setStatus(e.target.value)} aria-label="Filter by step" className="btn">
            <option value="all">All steps</option>
            {ALL_STATUSES.slice(1).map((s) => (
              <option key={s}>{s}</option>
            ))}
          </select>
        </div>
      </div>
      <ErrorNote error={error} />
      <div className="stack">
        {items === null && (
          <div className="card">
            <div className="skeleton" />
            <div className="skeleton" />
          </div>
        )}
        {items?.length === 0 && (
          <p className="empty card">{delivery === 'failed' ? 'No failed messages. Everything was delivered 🙏' : 'No messages yet.'}</p>
        )}
        {items?.map((n) => (
          <article key={n.id} className="card" style={{ padding: 16 }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap', marginBottom: 8 }}>
              <span>
                <Link href={`/bookings/${n.bookingId}`} className="mono">
                  {n.bookingId}
                </Link>{' '}
                · {n.devoteeName} · {n.to}
              </span>
              <StatusBadge status={n.status} />
            </div>
            <div className="chat">
              <MessageBubble
                message={n}
                canResend={can('notifications:resend')}
                onResent={(updated) => {
                  load();
                  setToast(updated.delivery.status === 'sent' ? 'Message delivered (mock)' : `Still failing: ${updated.delivery.error}`);
                  setTimeout(() => setToast(''), 3500);
                }}
              />
            </div>
          </article>
        ))}
      </div>
      {toast && <div className="toast">{toast}</div>}
    </>
  );
}

export default function NotificationsPage() {
  return (
    <Suspense fallback={null}>
      <NotificationsList />
    </Suspense>
  );
}
